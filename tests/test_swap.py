def test_plan_swap_native_in(state):
    p = lp.plan_swap(FakeW3(state), POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17)
    assert p["approvals"] == [] and p["simulated"] and p["feeBps"] == 25
    assert (p["swap"]["chainId"], p["swap"]["from"], p["swap"]["to"].lower(), p["swap"]["value"]) == (8453, ME, lp.KYBER_ROUTER, 10**17)
    assert p["minReturn"] >= p["quoteOut"] * 9_949 // 10_000


def test_plan_swap_token_in_needs_an_exact_approval(state):
    p = lp.plan_swap(FakeW3(state), {**POOL, "pairClass": "stable"}, owner=ME, from_side=1, amount_in=1_000_000_000, slippage_bps=10)
    assert len(p["approvals"]) == 1 and p["approvals"][0]["to"].lower() == USDC
    spender, amount = decode(["address", "uint256"], bytes.fromhex(p["approvals"][0]["data"][10:]))
    assert (spender.lower(), amount) == (lp.KYBER_ROUTER, 1_000_000_000)
    assert (p["simulated"], p["feeBps"]) == (False, 5)


def test_plan_swap_refusals(state):
    w3 = FakeW3(state)
    state["rate"] = 900
    with pytest.raises(lp.SwapRefused, match="impact"):
        lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17)
    state["rate"] = 998
    with pytest.raises(lp.SwapRefused, match="moved"):
        lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17, min_out=lp.spot_out(SP, True, 10**17, 25))
    state["looser"] = 20
    with pytest.raises(lp.SwapRefused, match=r"calldata\): minimum"):
        lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17)
    state["looser"], state["simulate"] = 0, "revert"
    with pytest.raises(lp.SwapRefused, match="simulation"):
        lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17)
    with pytest.raises(ValueError, match="v4"):
        lp.plan_swap(w3, {**POOL, "dex": "uniswap_v4"}, owner=ME, from_side=0, amount_in=1)
    with pytest.raises(ValueError, match="wrapped native"):
        lp.plan_swap(w3, POOL, owner=ME, from_side=1, from_native=True, amount_in=1)


def test_plan_swap_refuses_a_slippage_that_would_zero_the_minimum(state):
    w3 = FakeW3(state)
    for bad in (10_000, 20_000, -1, 0.5, True):
        with pytest.raises(ValueError, match="slippage_bps"):
            lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17, slippage_bps=bad)
    with pytest.raises(ValueError, match="min_out"):
        lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17, min_out=-1)
    assert state["calls"] == []  # nothing asked of the aggregator
    assert lp.plan_swap(w3, POOL, owner=ME, from_side=0, from_native=True, amount_in=10**17, slippage_bps=0)["minReturn"] > 0

