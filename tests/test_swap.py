"""lpsignal.liquidity's swap checks against the reference TypeScript implementation's vectors (tests/swap_vectors.json,
generated by lpsignal-node scripts/swap-vectors.mjs from a real KyberSwap build and tampered copies of it): every
verdict and every number must match; plus plan_swap with a fake chain and aggregator."""
import json
from pathlib import Path

import pytest
from eth_abi import decode, encode

from lpsignal import liquidity as lp

V = json.loads((Path(__file__).parent / "swap_vectors.json").read_text())


def n(x):
    if isinstance(x, str) and x.startswith("n") and x[1:].lstrip("-").isdigit():
        return int(x[1:])
    if isinstance(x, list):
        return [n(i) for i in x]
    if isinstance(x, dict):
        return {k: n(v) for k, v in x.items()}
    return x


def verdict(call, e):
    try:
        lp.check_swap_call(call, from_token=e["from"]["token"], from_native=e["from"]["native"], to_token=e["to"]["token"], to_native=e["to"]["native"],
                           amount_in=e["amountIn"], account=e["account"], fee_bps=e["feeBps"], min_out=e["minOut"])
        return None
    except lp.SwapRefused as x:
        return str(x)


def test_calldata_verdicts_match_typescript():
    for c in n(V["calls"]):
        assert verdict(c["call"], c["expect"]) == c["verdict"], c["name"]


def test_numbers_match_typescript():
    for sp, in0, a, f, want in n(V["spot"]):
        assert lp.spot_out(sp, in0, a, f) == want
    for s, i, sl, want in n(V["floor"]):
        assert lp.min_out_floor(s, i, sl) == want
    for s, i, sl, need, q, want in n(V["required"]):
        assert lp.required_min_out(s, i, sl, need, q) == want
    for c, fee, impact in V["classes"]:
        assert (lp.swap_fee_bps(c), lp.max_impact_bps(c)) == (fee, impact)
    assert lp.SWAP_FEE_RECEIVER == "0x13ac5bf01871ec16a9a5276f1e167da846af6a33"


# ---- plan_swap against a fake chain and aggregator ----
ME = "0x00000000000000000000000000000000000000aa"
WETH, USDC = "0x4200000000000000000000000000000000000006", "0x833589fcd6edb6e08f4c7c32d4f71b54bda02913"
POOL = {"chain": "base", "address": "0x6c561b446416e1a00e8e93e221854d6ea4171372", "dex": "uniswap_v3", "token0": WETH, "token1": USDC,
        "decimals0": 18, "decimals1": 6, "fee": 3000, "tickSpacing": 60, "pairClass": "volatile"}
TICK = -200000
SP = lp.sqrt_ratio_at_tick(TICK)


class FakeEth:
    def __init__(self, s):
        self.s, self.chain_id = s, 8453

    def call(self, tx, block_identifier="latest"):
        d = tx["data"]
        if d.startswith("0x" + lp._selector("slot0()").hex()):
            return encode(["uint160", "int24"], [SP, TICK])
        if d.startswith("0x" + lp._selector("allowance(address,address)").hex()):
            return encode(["uint256"], [self.s["allowance"]])
        if tx["to"].lower() == lp.KYBER_ROUTER:
            if self.s["simulate"] == "revert":
                raise ValueError("execution reverted")
            return encode(["uint256", "uint256"], [1, 1])
        raise AssertionError(d[:10])


class FakeW3:
    def __init__(self, s):
        self.eth = FakeEth(s)


